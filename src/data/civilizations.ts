export const CIVILIZATION_MAP: Record<string, Civilization> = Object.fromEntries(
  CIVILIZATIONS.map((civ) => [civ.id, civ])
);

export const CIVILIZATION_REGIONS: string[] = Array.from(
  new Set(
    CIVILIZATIONS.map((civ) => civ.region).filter(
      (region): region is string => typeof region === 'string' && region.length > 0
    )
  )
).sort();

export function getActiveCivilizationsForYear(year: number): Civilization[] {
  return CIVILIZATIONS.filter((c) => year >= c.startYear && year <= c.endYear);
}
